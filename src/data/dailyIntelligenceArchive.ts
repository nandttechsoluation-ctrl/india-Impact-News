// Master date-to-edition builder
export function getDailyNewsForDate(targetDateOrString?: Date | string, forceEditionIndex?: number): DailyEditionData {
  let date: Date;
  if (!targetDateOrString) {
    date = new Date();
  } else if (typeof targetDateOrString === 'string') {
    // If YYYY-MM-DD
    const parts = targetDateOrString.split('-');
    if (parts.length === 3) {
      date = new Date(parseInt(parts[0], 10), parseInt(parts[1], 10) - 1, parseInt(parts[2], 10));
    } else {
      date = new Date(targetDateOrString);
    }
  } else {
    date = targetDateOrString;
  }

  // Format date string YYYY-MM-DD in IST
  const dateStr = new Intl.DateTimeFormat('en-CA', { timeZone: 'Asia/Kolkata' }).format(date);

  const formattedEn = date.toLocaleDateString('en-IN', {
    weekday: 'long',
    year: 'numeric',
    month: 'short',
    day: 'numeric',
  });

  const formattedHi = date.toLocaleDateString('hi-IN', {
    weekday: 'long',
    year: 'numeric',
    month: 'long',
    day: 'numeric',
  });

  // Calculate day index from date components so that every single day rotates deterministically
  const dayOfMonth = date.getDate();
  const dayOfYear = Math.floor((date.getTime() - new Date(date.getFullYear(), 0, 0).getTime()) / (1000 * 60 * 60 * 24));

  // If forceEditionIndex is passed, use it; otherwise default to Day 0 (Today's Breaking US 100% Tariff Law & High-Impact Strategic edition)
  const editionIdx = typeof forceEditionIndex === 'number'
    ? Math.abs(forceEditionIndex) % 4
    : 0;

  switch (editionIdx) {
    case 0:
      return buildDay0Edition(dateStr, formattedEn, formattedHi);
    case 1:
      return buildDay1Edition(dateStr, formattedEn, formattedHi);
    case 2:
      return buildDay2Edition(dateStr, formattedEn, formattedHi);
    case 3:
    default:
      return buildDay3Edition(dateStr, formattedEn, formattedHi);
  }
}

